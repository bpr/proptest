"""Generate proptest/strategies/types.mojo: `from_type[T]()`.

    python3 tools/gen_from_type.py

The type dispatch is a long chain of `comptime if T == ...` branches (Mojo
cannot pattern-match a generic type like `List[E]` for an unknown `E`), so
it is generated rather than written by hand.
"""

from pathlib import Path

SCALARS = [
    ("Int", "integers()"),
    ("Int8", "integers_of[DType.int8]()"),
    ("Int16", "integers_of[DType.int16]()"),
    ("Int32", "integers_of[DType.int32]()"),
    ("Int64", "integers_of[DType.int64]()"),
    ("UInt", "integers_of[DType.uint]()"),
    ("UInt8", "integers_of[DType.uint8]()"),
    ("UInt16", "integers_of[DType.uint16]()"),
    ("UInt32", "integers_of[DType.uint32]()"),
    ("UInt64", "integers_of[DType.uint64]()"),
    ("Float64", "floats()"),
    ("Float32", "floats32()"),
    ("Bool", "booleans()"),
    ("String", "text()"),
]
# element types usable as Set elements / Dict keys
HASHABLE = [t for t, _ in SCALARS if not t.startswith("Float")]

branches = []
for t, s in SCALARS:
    branches.append((t, f"data.draw({s})"))
for t, _ in SCALARS:
    branches.append((f"List[{t}]", f"data.draw(lists(FromType[{t}]()))"))
for t, _ in SCALARS:
    branches.append((f"Optional[{t}]", f"data.draw(optionals(FromType[{t}]()))"))
for t in HASHABLE:
    branches.append((f"Set[{t}]", f"data.draw(sets(FromType[{t}]()))"))
for t, _ in SCALARS:
    branches.append(
        (f"Dict[String, {t}]", f"data.draw(dictionaries(text(), FromType[{t}]()))")
    )

# Nested containers, one level deep: List/Optional of List/Optional/Set
# of a scalar, and Dict[String, List[_]].
for t, _ in SCALARS:
    for outer, wrap in (("List", "lists"), ("Optional", "optionals")):
        for inner in ("List", "Optional"):
            branches.append(
                (f"{outer}[{inner}[{t}]]", f"data.draw({wrap}(FromType[{inner}[{t}]]()))")
            )
        if t in HASHABLE:
            branches.append(
                (f"{outer}[Set[{t}]]", f"data.draw({wrap}(FromType[Set[{t}]]()))")
            )
    branches.append(
        (
            f"Dict[String, List[{t}]]",
            f"data.draw(dictionaries(text(), FromType[List[{t}]]()))",
        )
    )

# Tuples (pairs and triples) of the most common element types, and lists of
# pairs. A Tuple's element types live in a parameter pack that reflection
# can't index, so each combination is a branch.
TUPLE_ELEMS = ["Int", "Int64", "UInt8", "Float64", "Bool", "String"]
for a in TUPLE_ELEMS:
    for b in TUPLE_ELEMS:
        branches.append(
            (
                f"Tuple[{a}, {b}]",
                f"data.draw(tuples(FromType[{a}](), FromType[{b}]()))",
            )
        )
        branches.append(
            (
                f"List[Tuple[{a}, {b}]]",
                f"data.draw(lists(FromType[Tuple[{a}, {b}]]()))",
            )
        )
TRIPLE_ELEMS = ["Int", "Float64", "Bool", "String"]
for a in TRIPLE_ELEMS:
    for b in TRIPLE_ELEMS:
        for c in TRIPLE_ELEMS:
            branches.append(
                (
                    f"Tuple[{a}, {b}, {c}]",
                    f"data.draw(tuples(FromType[{a}](), FromType[{b}](), FromType[{c}]()))",
                )
            )

chain = []
for i, (ty, expr) in enumerate(branches):
    kw = "elif"
    chain.append(f"    {kw} T == {ty}:\n        return rebind_var[T]({expr})")
chain_src = "\n".join(chain)
supported = ", ".join(f"`{t}`" for t, _ in SCALARS)

src = f'''# ===----------------------------------------------------------------------=== #
# proptest: property-based testing for Mojo.
# A port of Hypothesis (https://github.com/HypothesisWorks/hypothesis). MIT License; see LICENSE.
# ===----------------------------------------------------------------------=== #
"""Strategies inferred from types: `from_type[T]()` and `Arbitrary`.

Generated by tools/gen_from_type.py; edit that script, not this file.

Port of Hypothesis's `from_type`, `builds` and `register_type_strategy`, as
far as Mojo allows (see docs/differences-from-hypothesis.md, section 3.5).
Hypothesis inspects type annotations and `__init__` signatures at runtime;
proptest resolves the type at compile time:

1. a type that implements `Arbitrary` draws itself with its own
   `arbitrary(data)` (Hypothesis's `register_type_strategy`);
2. the scalar types {supported}, and `List`, `Optional`, `Set` and
   `Dict[String, _]` of them, use the corresponding strategy, as do one
   level of nesting (`List`/`Optional` of `List`/`Optional`/`Set`, and
   `Dict[String, List[_]]`), pairs of `Int`, `Int64`, `UInt8`, `Float64`,
   `Bool` and `String` (and lists of such pairs), and triples of `Int`,
   `Float64`, `Bool` and `String`;
3. any other struct is built field by field (like Hypothesis's
   `builds(Cls)` with every argument inferred), recursively, using
   compile-time reflection on its fields.

Building a struct from its fields writes each field directly: it does not
call `__init__`, so any invariant that `__init__` would establish is not.
Give such types an `Arbitrary` implementation instead. Types that contain
anything else (pointers, MLIR types, other tuples or containers) are a
compile-time error. (Mojo can't pattern-match a generic type such as
`List[E]` for an unknown `E`, or index a `Tuple`'s element types, so each
supported combination is a branch generated by tools/gen_from_type.py.)
"""

from std.collections import Set, Dict
from std.iter import downcast
from std.memory.alloc import unsafe_alloc
from std.reflection import reflect

from proptest.internal.data import ConjectureData, calc_label_from_name
from proptest.strategies.strategy import Strategy, Drawable
from proptest.strategies.core import (
    tuples,
    integers,
    integers_of,
    floats,
    floats32,
    booleans,
    text,
    lists,
    optionals,
    sets,
    dictionaries,
)


trait Arbitrary:
    """A type that knows how to draw itself (Hypothesis's
    `register_type_strategy`). `from_type` uses it in preference to
    anything else, including for fields of other structs.

    ```mojo
    @fieldwise_init
    struct Interval(Arbitrary, Copyable, Writable):
        var lo: Int
        var hi: Int

        @staticmethod
        def arbitrary(mut data: ConjectureData) raises -> Self:
            var lo = data.draw(integers(-100, 100))
            return Self(lo, data.draw(integers(lo, 100)))
    ```
    """

    @staticmethod
    def arbitrary(mut data: ConjectureData) raises -> Self:
        """Draw a value of this type."""
        ...


def draw_from_type[T: Copyable & Deinitable](mut data: ConjectureData) raises -> T:
    """Draw a value of type `T`, choosing the strategy at compile time."""
    comptime if conforms_to(T, Arbitrary):
        return rebind_var[T](downcast[T, Arbitrary].arbitrary(data))
{chain_src}
    else:
        comptime assert reflect[T].is_struct(), (
            "from_type: no strategy for this type; implement Arbitrary for it"
        )
        comptime types = reflect[T].field_types()
        comptime names = reflect[T].field_names()
        var p = unsafe_alloc[T](1)
        var base = p.unsafe_bitcast[UInt8]()
        try:
            comptime for i in range(reflect[T].field_count()):
                comptime FT = downcast[types[i], Copyable & Deinitable]
                # one span per field, so the shrinker can work field by field
                comptime field_name = names[i]
                data.start_span(calc_label_from_name(field_name))
                var v = draw_from_type[FT](data)
                data.stop_span()
                comptime offset = reflect[T].field_offset[index=i]()
                base.unsafe_offset(offset).unsafe_bitcast[FT]().unsafe_write(v^)
        except e:
            # The fields written so far are leaked rather than destroyed:
            # this only happens when a test case is abandoned (overrun or
            # filtered out), and the memory is small.
            p.unsafe_free()
            raise e^
        var out = p.unsafe_take_pointee()
        p.unsafe_free()
        return out^


struct FromType[T: Drawable](Copyable, Strategy):
    """Values of type `T`; see `from_type()`."""

    comptime Value = Self.T

    def __init__(out self):
        pass

    def label(self) -> UInt64:
        return calc_label_from_name(String("from_type:", reflect[Self.T].name()))

    def do_draw(self, mut data: ConjectureData) raises -> Self.T:
        return draw_from_type[Self.T](data)


def from_type[T: Drawable]() -> FromType[T]:
    """A strategy for values of type `T`, inferred from the type (Hypothesis's
    `from_type`; see this module's documentation for what is supported)."""
    return FromType[T]()
'''
out = Path(__file__).resolve().parent.parent / "proptest/strategies/types.mojo"
out.write_text(src)
print(f"wrote {out} with {len(branches)} type branches")
