"""Generate proptest/internal/charmap_data.mojo: the codepoint ranges of
every Unicode general category, from Python's `unicodedata`.

    python3 tools/gen_charmap.py

This plays the role of Hypothesis's `hypothesis/internal/charmap.py`, which
builds the same table from `unicodedata` at runtime (and caches it on disk).
Mojo's standard library has no Unicode category data, so the table is
generated once and checked in.
"""

import sys
import unicodedata
from pathlib import Path

ranges = {}
prev_cat = None
start = 0
for cp in range(sys.maxunicode + 1):
    cat = unicodedata.category(chr(cp))
    if cat != prev_cat:
        if prev_cat is not None:
            ranges.setdefault(prev_cat, []).append((start, cp - 1))
        prev_cat, start = cat, cp
ranges.setdefault(prev_cat, []).append((start, sys.maxunicode))

lines = []
for cat in sorted(ranges):
    parts = [f"{lo:x}" if lo == hi else f"{lo:x}-{hi:x}" for lo, hi in ranges[cat]]
    lines.append(cat + " " + " ".join(parts))

total = sum(len(v) for v in ranges.values())
out = Path(__file__).resolve().parent.parent / "proptest/internal/charmap_data.mojo"
out.write_text(
    "# ===----------------------------------------------------------------------=== #\n"
    "# proptest: property-based testing for Mojo.\n"
    "# A port of Hypothesis (https://github.com/HypothesisWorks/hypothesis). MIT License; see LICENSE.\n"
    "# ===----------------------------------------------------------------------=== #\n"
    '"""Codepoint ranges of each Unicode general category.\n\n'
    f"Generated by tools/gen_charmap.py from Unicode {unicodedata.unidata_version}\n"
    f"({len(ranges)} categories, {total} ranges). Do not edit by hand.\n"
    '"""\n\n'
    f'comptime UNICODE_VERSION = "{unicodedata.unidata_version}"\n\n'
    "comptime CATEGORY_DATA: StaticString = (\n"
    + "\n".join(f'    "{line}\\n"' for line in lines)
    + "\n)\n"
)
print(f"wrote {out}: {len(ranges)} categories, {total} ranges")


# --- decompositions, for the normalize_unicode_chars shrink pass ---------
# For each codepoint, the distinct characters of its NFD and NFKD forms and
# of its casefold (Hypothesis's `_natural_simpler_chars`; upper and lower
# case come from Mojo's String.upper()/lower() at run time).
entries = []
for cp in range(sys.maxunicode + 1):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if 0xAC00 <= cp <= 0xD7A3:
        continue  # Hangul syllables: decomposed algorithmically at run time
    c = chr(cp)
    found = []
    for form in (
        unicodedata.normalize("NFD", c),
        unicodedata.normalize("NFKD", c),
        c.casefold(),
    ):
        for d in form:
            if d != c and d not in found:
                found.append(d)
    if found:
        entries.append(f"{cp:x}:" + ",".join(f"{ord(d):x}" for d in found))

dout = Path(__file__).resolve().parent.parent / "proptest/internal/decomposition_data.mojo"
chunks = [" ".join(entries[i : i + 12]) for i in range(0, len(entries), 12)]
dout.write_text(
    "# ===----------------------------------------------------------------------=== #\n"
    "# proptest: property-based testing for Mojo.\n"
    "# A port of Hypothesis (https://github.com/HypothesisWorks/hypothesis). MIT License; see LICENSE.\n"
    "# ===----------------------------------------------------------------------=== #\n"
    '"""Characters in the NFD/NFKD decomposition and casefold of each codepoint.\n\n'
    f"Generated by tools/gen_charmap.py from Unicode {unicodedata.unidata_version}\n"
    f"({len(entries)} codepoints). Do not edit by hand. Each entry is\n"
    "`codepoint:component,component,...` in hex, entries separated by spaces.\n"
    '"""\n\n'
    "comptime DECOMPOSITION_DATA: StaticString = (\n"
    + "\n".join(f'    "{chunk} "' for chunk in chunks)
    + "\n)\n"
)
print(f"wrote {dout}: {len(entries)} codepoints")
